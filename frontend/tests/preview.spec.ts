import { test, expect } from '@playwright/test';

test('renders the native world and supports input, scan, lab, and mobile layout',async({page})=>{
  const errors:string[]=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto('/');
  await expect(page.getByRole('heading',{name:'A signal worth finding.'})).toBeVisible();
  await expect(page.locator('canvas')).toHaveAttribute('data-ready','true',{timeout:45000});
  await expect(page.locator('.renderer-error')).toHaveCount(0);
  await expect(page.locator('.engine-status')).not.toContainText('0 draws');
  const before=await page.locator('.coordinate strong').textContent();
  await page.locator('canvas').focus();
  await page.keyboard.down('KeyD');await page.waitForTimeout(600);await page.keyboard.up('KeyD');
  await expect(page.locator('.coordinate strong')).not.toHaveText(before!);
  await expect.poll(()=>page.evaluate(()=>(globalThis as any).__AURA3D_LIVE_APPS__.all()[0].nodes.require('pilot-0').position[0])).toBeGreaterThan(1);
  expect(await page.evaluate(()=>(globalThis as any).__AURA3D_LIVE_APPS__.all()[0].nodes.require('pilot-1').visible)).toBe(false);
  expect(await page.evaluate(()=>(globalThis as any).__AURA3D_LIVE_APPS__.all()[0].nodes.require('beam-0').visible)).toBe(false);
  await page.getByRole('button',{name:'Survey pulse'}).click();
  await expect(page.getByRole('status')).toContainText('Survey pulse');
  await page.screenshot({path:'../artifacts/relay-desktop.png',fullPage:true});
  await page.getByRole('button',{name:'Engine lab',exact:true}).first().click();
  await expect(page.getByRole('heading',{name:'Under the surface.'})).toBeVisible();
  await page.getByRole('button',{name:'Physics impulse'}).click();
  const physicsY=await page.evaluate(()=>{const app=(globalThis as any).__AURA3D_LIVE_APPS__.all()[0];return app.physics.bodies.require('physics-0').position()[1];});
  await page.waitForTimeout(500);
  const physicsAfter=await page.evaluate(()=>{const app=(globalThis as any).__AURA3D_LIVE_APPS__.all()[0];return app.physics.bodies.require('physics-0').position()[1];});
  expect(physicsY).not.toEqual(physicsAfter);
  await page.getByRole('combobox',{name:'Material',exact:true}).selectOption('metal');
  await page.waitForTimeout(1000);
  await expect(page.locator('.renderer-error')).toHaveCount(0);
  await page.screenshot({path:'../artifacts/relay-lab.png',fullPage:true});
  await page.getByRole('button',{name:'Capabilities',exact:true}).click();
  await expect(page.getByRole('dialog')).toContainText('More than a spinning cube.');
  await page.getByRole('button',{name:'Close dialog'}).click();
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:'../artifacts/relay-mobile.png',fullPage:true});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
  expect(errors).toEqual([]);
});
